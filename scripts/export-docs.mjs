import { writeFile, readdir } from "node:fs/promises";
import { QUESTION_BANK } from "../lib/engine/questions.ts";
await writeFile(
  new URL("../docs/QUESTION_BANK.json", import.meta.url),
  JSON.stringify(QUESTION_BANK, null, 2) + "\n",
);
const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");
await writeFile(
  new URL("../docs/QUESTION_BANK.md", import.meta.url),
  `# Question inventory\n\n${QUESTION_BANK.length} expanded questions. Generated from the runtime bank with \`npm run docs:generate\`. Full conditions, examples, destinations and validation are in QUESTION_BANK.json.\n\n| ID | Scope | Category | Question | Priority | Required |\n|---|---|---|---|---:|---|\n` +
    QUESTION_BANK.map(
      (q) =>
        `| ${cell(q.id)} | ${q.scope} | ${q.category} | ${cell(q.text)} | ${q.priority} | ${q.required ? "Yes" : "No"} |`,
    ).join("\n") +
    "\n",
);
const skip = new Set([
  "node_modules",
  "dist",
  ".git",
  ".wrangler",
  ".sites-runtime",
  ".next",
  ".vinext",
  ".agents",
  ".codex",
  "__qa",
  ".npmrc",
]);
const root = new URL("../", import.meta.url);
async function walk(dir = "") {
  const result = [];
  for (const e of await readdir(new URL(dir, root), { withFileTypes: true })) {
    if (
      skip.has(e.name) ||
      e.name.endsWith(".tsbuildinfo") ||
      (e.name.startsWith(".env") && e.name !== ".env.example")
    )
      continue;
    const p = dir + e.name;
    if (e.isDirectory()) result.push(...(await walk(p + "/")));
    else result.push(p);
  }
  return result;
}
const files = (await walk()).sort();
await writeFile(
  new URL("../docs/DIRECTORY.md", import.meta.url),
  "# Project directory\n\nFull file inventory, excluding dependencies, builds, local databases and runtime secrets. Generated by `npm run docs:generate`.\n\n| Directory | Files |\n|---|---|\n" +
    [
      ...new Set(
        files.map((p) =>
          p.includes("/") ? p.slice(0, p.lastIndexOf("/")) : ".",
        ),
      ),
    ]
      .map(
        (dir) =>
          `| ${dir} | ${files
            .filter(
              (p) =>
                (p.includes("/") ? p.slice(0, p.lastIndexOf("/")) : ".") ===
                dir,
            )
            .map((p) => "`" + p.split("/").at(-1) + "`")
            .join(", ")} |`,
      )
      .join("\n") +
    "\n",
);
console.log(
  `Documented ${QUESTION_BANK.length} questions and ${files.length} source files.`,
);
